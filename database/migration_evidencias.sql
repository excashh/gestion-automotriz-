-- Migración idempotente: Evidencia fotográfica por orden y servicio
-- Segura para ejecutar sobre una base de datos autopro_db ya existente.

ALTER TABLE servicios
  ADD COLUMN IF NOT EXISTS etapas_evidencia_obligatorias TEXT[] NOT NULL DEFAULT '{}';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'chk_servicios_etapas_evidencia'
  ) THEN
    ALTER TABLE servicios
      ADD CONSTRAINT chk_servicios_etapas_evidencia
      CHECK (etapas_evidencia_obligatorias <@ ARRAY[
        'antes_diagnostico',
        'durante_trabajo',
        'pieza_retirada',
        'despues_instalacion',
        'entrega'
      ]::TEXT[]);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS orden_evidencias (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id           INTEGER      NOT NULL REFERENCES ordenes_trabajo(id) ON DELETE RESTRICT,
  orden_servicio_id  INTEGER      REFERENCES orden_servicios(id) ON DELETE SET NULL,
  servicio_id        INTEGER      REFERENCES servicios(id) ON DELETE RESTRICT,
  subido_por         INTEGER      NOT NULL REFERENCES usuarios(id),
  etapa              VARCHAR(30)  NOT NULL
                     CHECK (etapa IN (
                       'antes_diagnostico',
                       'durante_trabajo',
                       'pieza_retirada',
                       'despues_instalacion',
                       'entrega'
                     )),
  descripcion        TEXT,
  ruta_archivo       VARCHAR(255) NOT NULL,
  nombre_original    VARCHAR(180) NOT NULL,
  mime_type          VARCHAR(40)  NOT NULL
                     CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  tamano_bytes       INTEGER      NOT NULL CHECK (tamano_bytes > 0 AND tamano_bytes <= 8388608),
  activo             BOOLEAN      NOT NULL DEFAULT TRUE,
  eliminado_por      INTEGER      REFERENCES usuarios(id),
  fecha_eliminacion  TIMESTAMPTZ,
  motivo_eliminacion VARCHAR(200),
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_orden_evidencias_orden    ON orden_evidencias (orden_id) WHERE activo = TRUE;
CREATE INDEX IF NOT EXISTS ix_orden_evidencias_servicio ON orden_evidencias (servicio_id) WHERE activo = TRUE;

-- Ejemplo por defecto: en "Cambio de Balatas Delanteras" exigir evidencia de antes y después
UPDATE servicios
SET etapas_evidencia_obligatorias = ARRAY['antes_diagnostico', 'despues_instalacion']
WHERE codigo = 'SRV-FRN-01'
  AND cardinality(etapas_evidencia_obligatorias) = 0;
